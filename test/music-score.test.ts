import { expect, it } from "vitest";
import { gameplayScore } from "../src/client/audio/score.ts";
import { OPENINGS } from "../src/client/game/opening/definitions.ts";
import { createGame } from "../src/server/engine/create.ts";
import { project } from "../src/server/engine/project.ts";
import { seatsFor, SEED, T0 } from "./helpers.ts";
import type { ScenarioId } from "../src/shared/game/state.ts";

const view = (scenario: ScenarioId) => project(createGame("score", seatsFor(2), SEED, T0, scenario), "a");
it("takes the train from investigation through blackout/fold to a reflective or failed ending", () => {
  const g = view("S01_LAST_TRAIN");
  expect(gameplayScore(g)).toBe("s01_ambient");
  g.sequence = { kind: "BLACKOUT", acks: [] };
  expect(gameplayScore(g)).toBe("s01_anomaly");
  g.phase = "ACT_2"; g.sequence = null;
  expect(gameplayScore(g)).toBe("s01_anomaly");
  g.sequence = { kind: "FOLD", acks: [] };
  expect(gameplayScore(g)).toBe("s01_escape");
  g.phase = "ENDING"; g.outcome = "TRUE_TICKET";
  expect(gameplayScore(g)).toBe("s01_ending");
  g.phase = "RESULTS"; g.outcome = "FAILED";
  expect(gameplayScore(g)).toBe("failure");
});
it("scores the city from rescue to rising water and evacuation using public boat readiness", () => {
  const g = view("S02_SUNKEN_CITY");
  expect(gameplayScore(g)).toBe("s02_city_ambient");
  g.phase = "ACT_2";
  expect(gameplayScore(g)).toBe("s02_rising");
  g.city!.boat.readyRound = 4;
  expect(gameplayScore(g)).toBe("s02_evacuation");
  g.city!.boat.readyRound = null; g.phase = "ACT_3";
  expect(gameplayScore(g)).toBe("s02_evacuation");
  g.phase = "ENDING"; g.outcome = "S02_EVACUATED";
  expect(gameplayScore(g)).toBe("s02_ending");
});
it("distinguishes the visible eras, then escalates paradox, rewrite and the final history choice", () => {
  const g = view("S03_INCIDENT_ZERO");
  expect(gameplayScore(g)).toBe("scenario03_2026_ambient");
  g.temporal!.locations.a.year = "Y1996";
  expect(gameplayScore(g)).toBe("scenario03_1996_ambient");
  g.phase = "ACT_2";
  expect(gameplayScore(g)).toBe("s03_past_paradox");
  g.temporal!.locations.a.year = "Y2026";
  expect(gameplayScore(g)).toBe("s03_paradox");
  g.phase = "ACT_3";
  expect(gameplayScore(g)).toBe("s03_rewrite");
  g.phase = "ACT_4";
  expect(gameplayScore(g)).toBe("s03_resolution");
  g.phase = "ENDING"; g.outcome = "S03_NO_TOMORROW";
  expect(gameplayScore(g)).toBe("failure");
});
it("follows auction rounds and public final stages without reacting to private bids or balances", () => {
  const g = view("S04_UNDERGROUND_AUCTION");
  expect(gameplayScore(g)).toBe("s04_auction_ambient");
  g.round = 4; expect(gameplayScore(g)).toBe("s04_bargains");
  g.round = 7; expect(gameplayScore(g)).toBe("s04_highstakes");
  g.auction!.final = { stage: "SETTLEMENT", players: {}, winnerId: null, tiedPlayerIds: [], showdown: null };
  expect(gameplayScore(g)).toBe("s04_settlement");
  g.auction!.final.stage = "AUCTION";
  expect(gameplayScore(g)).toBe("s04_sealed");
  g.auction!.final.players.a = { status: "BID_SUBMITTED", continued: false, balance: 50, converted: null, usable: 50, bid: 30, modifier: 0, effectiveBid: 30 };
  expect(gameplayScore(g)).toBe("s04_sealed");
  g.auction!.final.stage = "REVEAL";
  expect(gameplayScore(g)).toBe("s04_reveal");
  g.auction!.final.stage = "SHOWDOWN_PICK";
  expect(gameplayScore(g)).toBe("s04_sealed");
  g.phase = "RESULTS"; g.outcome = "S04_DEBT";
  expect(gameplayScore(g)).toBe("s04_reveal");
});
it("preserves intentional silence while giving cinematic developments a scored transition", () => {
  expect(OPENINGS.S01_LAST_TRAIN.mix("arrival", 2).theme).toBe("silence");
  expect(OPENINGS.S01_LAST_TRAIN.mix("tickets", 1).theme).toBe("intro_train");
  expect(OPENINGS.S02_SUNKEN_CITY.mix("water", 1).theme).toBe("s02_rising");
  expect(OPENINGS.S03_INCIDENT_ZERO.mix("records", 10).level).toBe(0);
  expect(OPENINGS.S03_INCIDENT_ZERO.mix("mission", 1).theme).toBe("s03_resolution");
  expect(OPENINGS.S04_UNDERGROUND_AUCTION.mix("invitation", 0).theme).toBe("silence");
  expect(OPENINGS.S04_UNDERGROUND_AUCTION.mix("auctioneer", 0).level).toBe(0);
  expect(OPENINGS.S04_UNDERGROUND_AUCTION.mix("auctioneer", 2).level).toBeGreaterThan(0);
});
